// ─── the mirror ────────────────────────────────────────────────────────────

type Case = {
  readonly id: string;
  readonly before: string;
  readonly good: string;
  /** The facts the captured reply lost, by their text in the record. */
  readonly missingBefore: readonly string[];
  /** Ruled-out terms the captured reply brought back. */
  readonly resurfacedBefore: readonly string[];
};

const CASES: readonly Case[] = [
  {
    id: 'convo-teacher-email-resend',
    before: BEFORE_TEACHER_EMAIL,
    good: GOOD_TEACHER_EMAIL,
    // It kept the two days and lost the addressee — the reply is about an email
    // rather than being one. See the finding in this file's header: on THIS
    // reply the fact dim is the weaker signal and `answerDepth` is the strong one.
    missingBefore: ['Teacher'],
    resurfacedBefore: [],
  },
  {
    id: 'convo-four-day-budget-list',
    before: BEFORE_BUDGET_LIST,
    good: GOOD_BUDGET_LIST,
    // Water silently gone from a printed budget, the income it is measured
    // against never stated, the annual car-tax figure dropped, Netflix rounded.
    // Four of his own figures, named — which is the point of reporting a list.
    missingBefore: ['2180', '31', '12.99', '245'],
    resurfacedBefore: [],
  },
  {
    id: 'convo-birthday-lunch-message',
    before: BEFORE_BIRTHDAY_MESSAGE,
    good: GOOD_BIRTHDAY_MESSAGE,
    missingBefore: ['8', 'sunday'],
    resurfacedBefore: ['saturday'],
  },
];

describe('★ the mirror: a reply that loses the conversation must score badly', () => {
  for (const c of CASES) {
    describe(c.id, () => {
      it('names exactly which facts the captured reply lost', () => {
        const spec = probe(c.id);
        const analysis = analyzeHistoryFactPreservation(spec.historyFactSources!, c.before);
        // A LIST, not a count: a count survives the derivation degenerating.
        expect(analysis.missing.map((f) => f.text)).toEqual(c.missingBefore);
        expect(analysis.score).toBeLessThan(1);
      });

      it('★ the good reply keeps everything, and the bad one does not — the dim separates them', () => {
        const spec = probe(c.id);
        const bad = analyzeHistoryFactPreservation(spec.historyFactSources!, c.before);
        const good = analyzeHistoryFactPreservation(spec.historyFactSources!, c.good);
        expect(good.missing.map((f) => f.text)).toEqual([]);
        expect(good.score).toBe(1);
        // The whole claim of the dim, in one line.
        expect(good.score! - bad.score!).toBeGreaterThan(0);
      });

      it('the good reply is good by the OTHER dims too, so it cannot be a stub', () => {
        // Without this, a two-line reply listing the figures and nothing else
        // would "pass" the mirror while being exactly the non-answer the corpus
        // bounces on.
        const spec = probe(c.id);
        expect(scoreDeliversFirst(spec, c.good)).toBe(1);
        expect(scoreAnswerDepth(spec, c.good)).toBe(1);
      });

      it('reads the ruled-out side the same way round', () => {
        const spec = probe(c.id);
        const terms = spec.historyRuledOut;
        if (terms === undefined) {
          // Asserted positively rather than skipped: an item with no ruled-out
          // term must also have nothing recorded as resurfacing, or the fixture
          // and the gate disagree about what this probe measures.
          expect(c.resurfacedBefore).toEqual([]);
          return;
        }
        expect(analyzeRuledOut(terms, c.before).resurfaced).toEqual(c.resurfacedBefore);
        expect(analyzeRuledOut(terms, c.good).resurfaced).toEqual([]);
        expect(analyzeRuledOut(terms, c.good).score).toBe(1);
      });
    });
  }

  it('★ scoreResult wires both dims — a reply is scored on them without a caller opting in', () => {
    // The dim can be perfect and still measure nothing if the composer forgot it.
    // This is the check that PR #93 and PR #107 both needed and did not have.
    for (const c of CASES) {
      const spec = probe(c.id);
      const scores = scoreResult(spec, ctx(c.before));
      expect(scores.preservesHistoryFacts, `${c.id} before`).not.toBeNull();
      expect(scores.preservesHistoryFacts!, `${c.id} before`).toBeLessThan(1);
      expect(scoreResult(spec, ctx(c.good)).preservesHistoryFacts, `${c.id} good`).toBe(1);
    }
  });

  it('★ stays null where no spans are named — silence, not a free pass', () => {
    const ungated = EVERYDAY_CONVERSATION_PROBES.filter((p) => !p.historyFactSources);
    expect(ungated.length).toBeGreaterThan(0);
    for (const spec of ungated) {
      expect(scoreResult(spec, ctx('anything at all')).preservesHistoryFacts).toBeNull();
    }
    for (const spec of EVERYDAY_CONVERSATION_PROBES.filter((p) => !p.historyRuledOut)) {
      expect(scoreResult(spec, ctx('anything at all')).honorsRuledOut).toBeNull();
    }
  });
});

describe('★ honorsRuledOut on the item whose corpus text demands token absence', () => {
  // `convo-air-fryer-doneness` is the clean case: its `goodAnswerLooksLike` says
  // "No thermometer anywhere in the answer", so absence is the corpus's own
  // criterion rather than our reading of it.
  const spec = probe('convo-air-fryer-doneness');

  it('0 for the bounce the corpus writes out in full', () => {
    // Quoted from the item's own bounce condition.
    const bounce =
      'The only reliable way to know chicken is safe is to use a meat thermometer to confirm 165°F.';
    expect(scoreResult(spec, ctx(bounce)).honorsRuledOut).toBe(0);
  });

  it('1 for a verdict that answers with his eyes, which is what he asked for', () => {
    const good = [
      'That is the normal kind. Pink right up against the bone in a thigh comes from the',
      'marrow pigment leaching into the meat, and it stays pink even when the meat is fully',
      'cooked through — it is not a doneness signal at all.',
      '',
      'The signal that matters is the juice. Press near the bone and look at what runs out:',
      'clear or faintly straw-coloured is done, pink or cloudy is not. If the juice runs',
      'clear and the meat pulls back off the bone end, you are fine. If you are unsure, give',
      'it another four or five minutes — thigh meat is forgiving and will not dry out.',
    ].join('\n');
    expect(scoreResult(spec, ctx(good)).honorsRuledOut).toBe(1);
  });

  it('catches the plural too, so a ban cannot be dodged by an -s', () => {
    expect(
      scoreResult(spec, ctx('Cheap instant-read thermometers are under £15 and worth it.')).honorsRuledOut,
    ).toBe(0);
  });

  it('★ does NOT fire on a word that merely starts the same — a prefix match would', () => {
    // The guard that keeps `spa` off "Spain" and "spare". Asserted on the live
    // term so the rule cannot be loosened into a prefix match unnoticed.
    expect(
      scoreResult(spec, ctx('Thermometric probes are a different thing entirely.')).honorsRuledOut,
    ).toBe(1);
  });
});
