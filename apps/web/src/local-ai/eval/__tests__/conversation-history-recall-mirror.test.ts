/**
 * ★ THE MIRROR TEST for the two conversation-recall dims — a reply that loses
 * what the conversation already established must score BADLY, and one that keeps
 * it must score 1.0.
 *
 * WHAT THIS GUARDS. `preservesHistoryFacts` and `honorsRuledOut` were built to
 * catch one failure class: a fact or instruction given in an earlier turn getting
 * dropped, superseded or contradicted in the reply to a later turn. A dim that
 * has not been shown to catch the failure it names is not trustworthy however
 * reasonable its code looks — the standing rule in this repo — and both of these
 * are easy to satisfy by accident. So this file points them at real failures and
 * asserts they move.
 *
 * ── WHY THE BAD REPLIES ARE NOT SYNTHETIC ───────────────────────────────────
 *
 * They are the shipping default's ACTUAL output. Every `BEFORE_*` fixture below
 * was generated by `candidate/qwen3.5-2b-onnx` through the diagnostics harness
 * (`/diagnostics/local-ai?eco-diagnostics=1&eco-eval-autorun=1&eco-eval-prompts=…`),
 * greedy decode, 1536-token cap, on the probes this file scores — copied out of
 * the persisted run, not written here. A hand-written "bad reply" tests the
 * example; a captured one tests the instrument against the thing it exists for.
 *
 * The GOOD replies are hypothetical and this file says so plainly. They are
 * constrained rather than trusted: each one has to clear `deliversFirst` and the
 * probe's own richness floor (`answerDepth`) as well, so a stub that games only
 * the new dims cannot pass, and each is asserted to keep the ruled-out terms out.
 *
 * ── ONE FINDING, STATED RATHER THAN ROUNDED OFF ─────────────────────────────
 *
 * `preservesHistoryFacts` is NOT the sharpest dim on every one of these. On the
 * teacher-email refusal it reads 0.67, because the reply names Thursday and
 * Friday while refusing to produce the email — a fact dim cannot see a withheld
 * deliverable, and this one is documented as one-sided for exactly that reason.
 * `answerDepth` is what catches that reply (0.62 against a 60-word floor). The
 * assertions below are therefore about what each dim can actually see, and the
 * budget/birthday cases — where facts really do vanish — are where the fact dim
 * carries the finding on its own.
 */

import { describe, expect, it } from 'vitest';

import { EVERYDAY_CONVERSATION_PROBES } from '../everyday-conversation-probes';
import {
  analyzeHistoryFactPreservation,
  analyzeRuledOut,
  scoreAnswerDepth,
  scoreDeliversFirst,
  scoreResult,
} from '../rubric';
import type { EvalPromptSpec, RubricContext } from '../types';

function probe(id: string): EvalPromptSpec {
  const found = EVERYDAY_CONVERSATION_PROBES.find((p) => p.id === `everyday-convo-${id}`);
  if (!found) throw new Error(`no probe for ${id}`);
  return found;
}

/** A clean generation context: the reply is judged, not the stream around it. */
function ctx(output: string): RubricContext {
  return { output, endedCleanly: true, hitTokenCap: false };
}

